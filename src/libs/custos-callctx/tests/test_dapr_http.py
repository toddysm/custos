"""Actual HTTPX requests and redirects enforce the local API-token trust boundary."""

import httpx
import pytest

from custos_callctx.dapr_http import configure_dapr_http, dapr_http_client


@pytest.mark.parametrize("host", ["localhost", "127.0.0.1", "[::1]"])
async def test_local_token_never_follows_upstream_redirects(host: str) -> None:
    """Secret-store requests authenticate locally; external and redirected hops never receive it."""
    seen: list[tuple[str, str | None]] = []

    def handle(request: httpx.Request) -> httpx.Response:
        """Record actual transport headers, including the redirect generated by HTTPX."""
        seen.append((str(request.url), request.headers.get("dapr-api-token")))
        if request.url.path == "/v1.0/secrets/redirect":
            return httpx.Response(302, headers={"location": "https://provider.test/material"})
        return httpx.Response(200, json={})

    async with httpx.AsyncClient(
        transport=httpx.MockTransport(handle), follow_redirects=True, trust_env=False
    ) as client:
        configure_dapr_http(client, {"DAPR_API_TOKEN": "unit-api-token"})
        await client.get(f"http://{host}:3500/v1.0/secrets/redirect")
        await client.get(
            "https://provider.test/direct", headers={"dapr-api-token": "unit-api-token"}
        )
        await client.get(f"http://{host}:3501/v1.0/secrets/wrong-port")
        await client.get(f"http://{host}:3500/unrelated")
    assert seen[0][1] == "unit-api-token"
    assert all(token is None for _, token in seen[1:])


@pytest.mark.parametrize(
    "env",
    [
        {"DAPR_API_TOKEN": ""},
        {"DAPR_API_TOKEN": "token", "DAPR_HTTP_HOST": "provider.test"},
        {"DAPR_API_TOKEN": "token", "DAPR_HTTP_PORT": "0"},
    ],
)
async def test_invalid_token_transport_configuration_is_explicit(env: dict[str, str]) -> None:
    """Misconfiguration fails before opening a socket rather than dropping authentication."""
    async with httpx.AsyncClient() as client:
        with pytest.raises(ValueError):
            configure_dapr_http(client, env)


async def test_no_token_keeps_legacy_transport_unchanged() -> None:
    """Disabled secure transport does not install hooks or manufacture a credential."""
    async with httpx.AsyncClient() as client:
        assert configure_dapr_http(client, {}) is client
        assert client.event_hooks["request"] == []


async def test_environment_proxy_cannot_receive_local_api_credentials(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A logical loopback URL must not be sent through an ambient external HTTP proxy."""
    monkeypatch.setenv("HTTP_PROXY", "http://proxy.invalid:8080")
    env = {"DAPR_API_TOKEN": "unit-api-token"}
    async with httpx.AsyncClient() as unsafe:
        with pytest.raises(ValueError, match="proxy routing"):
            configure_dapr_http(unsafe, env)
    async with dapr_http_client(env=env) as safe:
        assert safe.trust_env is False
        assert len(safe.event_hooks["request"]) == 1
